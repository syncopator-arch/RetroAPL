#!/bin/bash
#
# package-source.sh
#
# Produce a distributable snapshot of the source tree: everything needed
# to check out and build on another machine (Linux now, Windows/Pi later),
# nothing that's a local build artifact or stray dev file.
#
# Replaces the old `aplpackage` script, which tarred a fixed glob list
# and missed build.sh, the font asset, and INSTALL.md, while also being
# unable to distinguish build artifacts from source.
#
# Usage: ./package-source.sh [output-basename]
# Produces <output-basename>.tar.gz in the current directory.
#
# Run from the repo root (sibling of backend/ and frontend/).

set -e

REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
OUTF="${1:-apl-source-$(date +%Y%m%d)}"

STAGE="$(mktemp -d)"
trap 'rm -rf "$STAGE"' EXIT
DEST="$STAGE/$OUTF"
mkdir -p "$DEST"

# Whitelist by extension/name, per directory, rather than blacklist --
# the tree has accumulated enough .save/.orig/.errs/archive/snapshot
# cruft (see backend/removed/, backend/archivedocs/, *.tar.gz, w64.errs,
# winsnap, etc. in buildtree.txt) that a blacklist would be a losing
# game of whack-a-mole. If something you need is missing from the
# output, it's because it didn't match a whitelist pattern below --
# add a pattern rather than switching to a blacklist.
copy_matching() {
    local srcdir="$1" destdir="$2"
    shift 2
    [ -d "$srcdir" ] || return 0
    mkdir -p "$destdir"
    find "$srcdir" -maxdepth 1 -type f \( "$@" \) -print0 \
        | xargs -0 -I{} cp {} "$destdir"/
}

# --- backend/ -------------------------------------------------------------
# Source + build file only. Explicitly NOT included: lib_objs/, stub_objs/,
# libapl.a, stub_test (build artifacts -- regenerated by build.sh/make),
# removed/, archivedocs/ (superseded snapshots), *.tar.gz.
copy_matching "$REPO_ROOT/backend" "$DEST/backend" \
    -name '*.c' -o -name '*.h' -o -name 'makefile' -o -name 'Makefile'

# Known-current docs only. The backend directory also holds several
# V-numbered / dated planning snapshots (PORTING_PLAN_V33.md,
# apl_session_context_V31.md, GRAPHICS_PLAN_V1.md, etc.) and note/issue
# files whose current relevance wasn't confirmed -- left out by default.
# Add them explicitly below if they should travel with the source.
for doc in BUILD.md INSTALL.md PORTING_LOG.md PORTING_PLAN.md \
           TESTING.md CLEANUP_STATUS.md; do
    [ -f "$REPO_ROOT/backend/$doc" ] && cp "$REPO_ROOT/backend/$doc" "$DEST/backend/"
done

# Test tooling (see TESTING.md). `make check` runs run_tests.sh.
# strip_ifdefs.sh is deliberately not listed: it was a one-time tool.
for tool in run_tests.sh; do
    [ -f "$REPO_ROOT/backend/$tool" ] && cp "$REPO_ROOT/backend/$tool" "$DEST/backend/"
done

# Regression tests: inputs, recorded transcripts, and .fn fixtures.
# Explicitly NOT included: tests/*.out (left behind by failed or new
# tests -- run output, not source).
copy_matching "$REPO_ROOT/backend/tests" "$DEST/backend/tests" \
    -name '*.apl' -o -name '*.expected'
copy_matching "$REPO_ROOT/backend/tests/fns" "$DEST/backend/tests/fns" \
    -name '*.fn'

# --- frontend/ --------------------------------------------------------------
# Explicitly NOT included: build/ (build artifact directory).
copy_matching "$REPO_ROOT/frontend" "$DEST/frontend" \
    -name '*.cpp' -o -name '*.h' -o -name '*.hpp' -o -name 'CMakeLists.txt' \
    -o -name 'build.sh' -o -name '*.bat' -o -name '*.md'

# --- font asset -------------------------------------------------------------
# Needed by build.sh's font-deploy step (ensure_font_deployed()), which
# looks for it at ../fonts/kapl.ttf relative to frontend/.
if [ -f "$REPO_ROOT/fonts/kapl.ttf" ]; then
    mkdir -p "$DEST/fonts"
    cp "$REPO_ROOT/fonts/kapl.ttf" "$DEST/fonts/"
else
    echo "Warning: $REPO_ROOT/fonts/kapl.ttf not found -- omitted" >&2
fi

# --- packaging tooling itself ------------------------------------------------
# So a machine built from this snapshot has the same build/package scripts,
# not just the application source.
for tool in package-source.sh package-install-linux.sh package-install-windows.bat; do
    [ -f "$REPO_ROOT/$tool" ] && cp "$REPO_ROOT/$tool" "$DEST/"
done

# plain `cp` doesn't preserve the executable bit, and it's easy for a
# checked-in script to have lost it already (see build.sh needing a
# manual chmod +x after an earlier delivery) -- set it explicitly for
# every script we know must be runnable, rather than trusting the source
# copy's permissions.
for script in "$DEST/frontend/build.sh" "$DEST/package-source.sh" "$DEST/package-install-linux.sh" \
              "$DEST/backend/run_tests.sh"; do
    [ -f "$script" ] && chmod +x "$script"
done

tar -czf "$OUTF.tar.gz" -C "$STAGE" "$OUTF"
echo "Created $OUTF.tar.gz ($(du -h "$OUTF.tar.gz" | cut -f1))"
echo ""
echo "Contents:"
( cd "$STAGE" && find "$OUTF" -type f | sort )
