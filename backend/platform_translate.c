/*
	platform_translate.c

	Shared APL character-translation layer, used identically by both
	linux_platform.c and windows_platform.c.

	Split out from those two files after a diff confirmed they carried
	byte-for-byte identical tables and functionally identical logic here
	(the only differences were a handful of missing comments and one
	unused variable in linux_platform.c). Keeping one copy removes the
	risk that this content drifts between platforms again the way
	itrans[0xE2] briefly did -- see the V33 porting-plan notes on the
	Cap+Circle/Execute overstrike bug this caused.

	Covers:
	  1. Keyboard/font/internal translation tables
	  2. Basic char-translation helpers
	  3. alt_input_proc() -- live keyboard/overstrike translation
	  4. file_translate() -- .fn file translation
	  (also: last_input_line() and text_translate(), for )FSEARCH, V77)

	Built and linked into both the Linux and Windows targets; nothing in
	this file is platform-specific.
*/

