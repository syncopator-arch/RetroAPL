UCHAR untrans_char(UCHAR c)
{
    return otrans[c];
}

UCHAR unktrans_char(UCHAR c)
{
    return kinverse[c];
}

/*
 * ucstrncmp() - case-insensitive strncmp, same as msdos.c.
 * Used by alt_input_proc() for system variable lookup.
 */
int ucstrncmp(UCHAR *s1, UCHAR *s2, int ct)
{
    UCHAR ch;
    while (ct--) {
        ch = *s2++;
        if (ch >= 'A' && ch <= 'Z') ch += 32;
        else if (ch >= 'a' && ch <= 'z') ch -= 32;
        if (*s1 > ch) return 1;
        if (*s1 < ch) return -1;
        s1++;
    }
    return 0;
}

/*
 * translate_init() - Initialize keyboard translation tables.
 * Called from the frontend (Qt) with the keyboard mapping table.
 * 
 * In the original Windows code, this was called with OrigTrans from Delphi.
 * For the Linux port, the Qt frontend will call this with its keyboard table.
 * 
 * If called with NULL, uses the internal orig_trans table.
 *
 * NOTE: msdos.c's translate_init() also ran `otrans[itrans[i]] = i;` here,
 * rebuilding otrans[] as the runtime inverse of itrans[] (itrans[] isn't
 * one-to-one, so this changes ~34 entries from the static initializer,
 * e.g. otrans[CHAR_EQ] from 0x01 to the real '=' display glyph 0x3d).
 * That line was already absent by the time this file was split out of
 * linux_platform.c -- not reintroduced here. untrans_char()/otrans[] have
 * no callers anywhere in the current source outside this file, the two
 * platform files, and their own extern declaration in externs.h, which
 * points at this being unreferenced leftover machinery from a bytecode
 * decompile-to-listing feature (APL\360-style) that was scrapped in favor
 * of maintaining the source file directly -- see V33 session notes. Both
 * functions are already on the list for a future dead-code cleanup pass;
 * if that pass finds a live caller after all, restore the line above
 * before trusting otrans[] for output.
 */
void translate_init(UCHAR *kt)
{
    int i, t;

    if (kt == NULL) {
        kt = (UCHAR *)orig_trans;
    }

    for (i = 0; i < 256; i++) {
        t = i;
        ktrans[i] = *kt++;
        /* Build inverse table with case flipping */
        if (i >= 'A' && i <= 'Z') t += 32;
        else if (i >= 'a' && i <= 'z') t -= 32;
        kinverse[i] = (UCHAR)t;
    }
    /* Complete the inverse mapping */
    for (i = 0; i < 256; i++) {
        kinverse[ktrans[i]] = (UCHAR)i;
    }

    translate_initialized = 1;
}

/*
 * ensure_translate_init() - Auto-initialize if not already done.
 * Called from file_translate() on first use.
 */
static void ensure_translate_init(void)
{
    if (!translate_initialized) {
        translate_init(NULL);
    }
}

/* ============================================================
   3. alt_input_proc() - Second stage of .fn file translation
   Direct port of msdos.c alt_input_proc()
   Used by: file_translate(), exec.c proc_quad(), and both front
   ends (main.cpp EngineThread::run(), apl_cli.c) for every line
   typed at the prompt

   The translation itself is input_translate(). alt_input_proc() is
   the entry for typed input: it records the line in the crash log's
   session transcript (crashlog.c), then translates it.
   file_translate() calls input_translate() directly, so .fn file
   lines read by )ENTER are not recorded -- they would crowd the
   typed session out of the transcript.

   What arrives here is a whole line, sent when Enter was pressed,
   with any backspace-overstrike composition and line editing already
   done by the front end (there is no backspace handling below), so
   the transcript shows lines as entered, not keystrokes.
   ============================================================ */

static int input_translate(UCHAR *cp, UCHAR *outs);

/*
   The last line alt_input_proc() was given, untranslated (font-index
   bytes), for )FSEARCH (commands.c do_fsearch(), V77). A command
   reaches do_command() already translated, and translation isn't
   one-to-one: itrans[] maps '$' and ⍞ both to '$', '-' and ¯ both to
   '-', and a few more pairs, so the search needs the text as typed.
*/
static UCHAR last_input[LINE_SIZE];

const UCHAR *last_input_line(void)
{
    return last_input;
}

/* input_translate() without the transcript recording, for checking
   that last_input_line() really is the line being run (do_fsearch()) */
int text_translate(UCHAR *cp, UCHAR *outs)
{
    return input_translate(cp, outs);
}

int alt_input_proc(UCHAR *cp, UCHAR *outs)
{
    crash_record_input(cp);
    strncpy((char *)last_input, (char *)cp, LINE_SIZE - 1);
    last_input[LINE_SIZE - 1] = '\0';
    return input_translate(cp, outs);
}

static int input_translate(UCHAR *cp, UCHAR *outs)
{
    UCHAR *sp = outs;
    UCHAR *cpt;
    UCHAR c;
    int inq, i, j, k;

    inq = 0;
    sp = outs;

    while (*cp) {
        if (*cp == 10 || *cp == 13) break;

        if (*cp == QUOTE_CHAR) {
            inq = 1 - inq;
            *sp++ = itrans[*cp++];
        } else if (inq) {
            *sp++ = *cp++;
        } else if (*cp == FONT_COMMENT) {
            break;		/* comment: rest of line ignored, unless quoted */
        } else {
            /* Overstrike pairs (from msdos.c) */
            if (*cp == 0xec && cp[1] == 0xfb) {
                *sp++ = CHAR_QTAS;
                cp += 2;
                continue;
            }
            if (*cp == 0xcc && cp[1] == 0xfb) {
                *sp++ = CHAR_QDAS;
                cp += 2;
                continue;
            }
            if (*cp == 0xca && cp[1] == '.') {
                *sp++ = CHAR_OUT;
                cp += 2;
                continue;
            }

            /* System variable lookup (quad + function name) */
            if (*cp == 0xcc) {
                c = *cp++;
                k = 0;
                cpt = all_fnames[k];
                while (cpt) {
                    j = 0;
                    while (*cpt) {
                        i = strlen((char *)cpt);
                        if (!ucstrncmp(cpt, cp, i)) {
                            c = cp[i];
                            if (c >= 'A' && c <= 'Z') c += 32;
                            if (!is_varch(c)) {
                                *sp++ = (UCHAR)CHAR_SYS;
                                c = j + (k << SYSFUNC_SHIFT);
                                cp += i;
                                goto sfound;
                            }
                        }
                        cpt += i + 1;
                        j++;
                    }
                    k++;
                    cpt = all_fnames[k];
                }
sfound:
                if (!cpt) c = CHAR_QD;
                *sp++ = c;
            } else {
                *sp++ = itrans[*cp++];
            }
        }
    }

    *sp-- = '\0';
    while (sp >= outs && *sp == ' ') {
        *sp-- = '\0';
    }

    return (int)strlen((char *)outs);
}

/* ============================================================
   4. file_translate() - Called from commands.c do_enter()
   Direct port of msdos.c file_translate()
   ============================================================ */

int 
file_translate(UCHAR *cp, UCHAR *outs)
{
    static UCHAR pxbuf[LINE_SIZE];
    UCHAR *px = pxbuf;

    ensure_translate_init();

    while (*cp) {
        UCHAR mapped = ktrans[*cp];
        *px++ = mapped;
        cp++;
    }
    *px-- = '\0';

    while (px >= pxbuf && *px == ' ') {
        *px-- = '\0';
    }

    return input_translate(pxbuf, outs);	/* not recorded: see section 3 */
}
