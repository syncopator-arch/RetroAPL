// -----------------------------------------------------------------------------
// Table 3: Overstrike Translation Table (OSTab)
// -----------------------------------------------------------------------------
// This table defines how two characters combine when using backspace-overstrike.
// Format: {char1, char2, result}
//
// BIDIRECTIONAL: The matching logic checks both (A,B) and (B,A) combinations,
// so order doesn't matter in this table.
//
// Source: Unit1.pas lines 186-209 (verified correct)
// Note: The domino entry (0xCC, 0xDF, 0xAD) is known to not work because
// the domino symbol is missing from KAPL.ttf
//
// V22 change: All four entries that used '|' (0x7C) as an operand have been
// updated to 0xCD (stile).  Since both the ASCII '|' key and shift-M now
// produce font index 0xCD, font index 0x7C can no longer appear in the
// display buffer from any keypress, making the old 0x7C entries permanently
// unreachable.
// -----------------------------------------------------------------------------

struct OverstrikeRule {
    uint8_t charA;
    uint8_t charB;
    uint8_t result;
};

const OverstrikeRule OSTab[] = {
    {0x27, 0xCC, 0xEC},     // ' + Quad = Quote-Quad
    {0xCF, 0xCD, 0xF7},     // Circle + Stile = Rotate           (was '|'/0x7C)
    {0xCF, '\\', 0xF4},     // Circle + Backslash = Transpose
    {0xCF, '-',  0xE1},     // Circle + Minus = Circle-Minus (vertical flip)
    {0xC2, 0xCE, 0xE0},     // Cap + Iota = I-Beam
    {0xCD, 'S',  '$'},      // Stile + S = Dollar                 (was '|'/0x7C)
    {0xCD, 0xC7, 0xE7},     // Stile + Del-down = Sort Descend   (was '|'/0x7C)
    {0xCD, 0xC8, 0xE8},     // Stile + Del-up = Sort Ascend      (was '|'/0x7C)
    {0xC8, '_',  0xFC},     // Del-up + Underbar = Del with underbar
    {0x27, '.',  '!'},      // Quote + Period = Exclamation
    {0xC2, 0xCA, 0xE2},     // Cap + Circle = Execute
    {0xC3, 0xCA, 0xE3},     // Down-U + Circle = Comment
    {',',  '-',  0xAC},     // comma + minus
    {0xCC, 0xDF, 0xAD},     // Quad + Divide = Domino (NOT WORKING - no glyph in font)
    {'~',  0xA1, 0xAE},     // tilde + dots, = selfie
    {'/',  '-',  0xAF},     // Slash + Minus = Compress with dash
    {'\\', '-',  0xDC},     // Backslash + Minus = Expand with dash
    {'^',  '~',  0xB0},     // Caret + Tilde = Nand
    {0xA9, '~',  0xB9},     // Or-symbol + Tilde = Nor
    {'*',  0xCF, 0xF0},     // Asterisk + Circle = Circle-Asterisk
    {0xC7, '~',  0xE6},     // Del-down + Tilde = Locked Del
    {0xCE, 0xCA, 0xEE},     // Decode + Circle = Format
    {'[',  ']',  0xBE},     // LBracket + RBracket = Squad
    {'^',  0xA9, 0xFE},     // Caret + Or-symbol = Diamond
    {0x00, 0x00, 0x00}      // Sentinel (end of table)
};

// Helper function to apply overstrike rules
// Returns the composed character if found, otherwise returns newChar
inline uint8_t applyOverstrike(uint8_t existing, uint8_t newChar) {
    for (int i = 0; OSTab[i].charA != 0x00; i++) {
        // Check both orderings (bidirectional)
        if ((existing == OSTab[i].charA && newChar == OSTab[i].charB) ||
            (existing == OSTab[i].charB && newChar == OSTab[i].charA)) {
            return OSTab[i].result;
        }
    }
    // No match found - new character replaces old
    return newChar;
}

